import mongoose from 'mongoose';
import dotenv from 'dotenv';
dotenv.config();

import { AuditLog, SalesInvoice, Voucher, StockAdjustment, Company } from '../models';

async function backfill() {
  const uri = process.env.MONGODB_URI || 'mongodb://localhost:27017/supermarket_inventory';
  await mongoose.connect(uri);
  console.log('Connected to MongoDB for audit log backfill');

  const defaultCompany = await Company.findOne().lean();
  const defaultCompanyId = defaultCompany?._id;

  // 1. Update existing login logs to have companyId if missing
  if (defaultCompanyId) {
    const resLogins = await AuditLog.updateMany(
      { companyId: { $exists: false } },
      { $set: { companyId: defaultCompanyId } }
    );
    console.log(`Updated ${resLogins.modifiedCount} existing audit logs with default companyId`);
  }

  const pad = (n: number) => n.toString().padStart(2, '0');
  const formatTime = (d: Date) => `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
  const formatDate = (d: Date) => `${pad(d.getDate())}/${pad(d.getMonth() + 1)}/${d.getFullYear()}`;

  // 2. Backfill Sales Invoices
  const invoices = await SalesInvoice.find().lean();
  let invCreated = 0;
  for (const inv of invoices) {
    const exists = await AuditLog.findOne({ entityId: inv._id.toString() });
    if (!exists) {
      const d = inv.createdAt ? new Date(inv.createdAt) : new Date(inv.date || Date.now());
      const formName = inv.type === 'POS' ? 'POS Cash Sales' : 'Sales Invoice';
      const vType = inv.paymentType || inv.type || 'Cash Sale';
      await AuditLog.create({
        companyId: inv.companyId || defaultCompanyId,
        userId: inv.createdBy,
        timestamp: d,
        form: formName,
        entityType: 'SalesInvoice',
        entityId: inv._id.toString(),
        action: 'Saved',
        entryNo: inv.invoiceNo || 'INV-' + inv._id.toString().slice(-6),
        salesType: vType,
        voucherType: vType,
        editedDate: formatDate(d),
        editedTime: formatTime(d),
        eventTime: formatTime(d),
        oldAmount: 0,
        newAmount: inv.totalAmount || inv.grossAmount || 0,
        systemName: 'POS-TERM-01',
        details: `Sales Invoice ${inv.invoiceNo || ''} - ${inv.customerName || 'Cash Customer'}`,
        after: {
          invoiceNo: inv.invoiceNo,
          grandTotal: inv.totalAmount,
          customerName: inv.customerName,
        },
      });
      invCreated++;
    }
  }
  console.log(`Backfilled ${invCreated} SalesInvoice audit logs`);

  // 3. Backfill Vouchers (exclude vouchers already generated by sales if any, or keep them)
  const vouchers = await Voucher.find().lean();
  let vchCreated = 0;
  for (const vch of vouchers) {
    const exists = await AuditLog.findOne({ entityId: vch._id.toString() });
    if (!exists) {
      const d = vch.createdAt ? new Date(vch.createdAt) : new Date(vch.date || Date.now());
      let formName = 'Journal Entry';
      if (vch.voucherType === 'Purchase') formName = 'Purchase Entry';
      else if (vch.voucherType === 'Payment') formName = 'Payment Voucher';
      else if (vch.voucherType === 'Receipt') formName = 'Receipt Voucher';
      else if ((vch.voucherType as string) === 'SalesReturn') formName = 'Sales Return';
      else if ((vch.voucherType as string) === 'PurchaseReturn') formName = 'Purchase Return';
      else if (vch.voucherType === 'Sales') formName = 'Sales Invoice';

      const vType = vch.voucherType || 'Voucher';
      const amount = vch.totalDebit || vch.totalCredit || 0;
      await AuditLog.create({
        companyId: vch.companyId || defaultCompanyId,
        userId: vch.createdBy,
        timestamp: d,
        form: formName,
        entityType: 'Voucher',
        entityId: vch._id.toString(),
        action: 'Saved',
        entryNo: vch.voucherNo || vch.referenceNo || 'VCH-' + vch._id.toString().slice(-6),
        salesType: vType,
        voucherType: vType,
        editedDate: formatDate(d),
        editedTime: formatTime(d),
        eventTime: formatTime(d),
        oldAmount: 0,
        newAmount: amount,
        systemName: 'POS-TERM-01',
        details: `${formName} ${vch.voucherNo || ''} ${vch.narration ? '- ' + vch.narration : ''}`,
        after: {
          voucherNo: vch.voucherNo,
          voucherType: vch.voucherType,
          grandTotal: amount,
        },
      });
      vchCreated++;
    }
  }
  console.log(`Backfilled ${vchCreated} Voucher audit logs`);

  // 4. Backfill Stock Adjustments
  const adjustments = await StockAdjustment.find().lean();
  let adjCreated = 0;
  for (const adj of adjustments) {
    const exists = await AuditLog.findOne({ entityId: adj._id.toString() });
    if (!exists) {
      const d = adj.createdAt ? new Date(adj.createdAt) : new Date(adj.date || Date.now());
      const amount = adj.netAdjustmentValue || adj.totalGainValue || adj.totalLossValue || 0;
      await AuditLog.create({
        companyId: adj.companyId || defaultCompanyId,
        userId: adj.createdBy,
        timestamp: d,
        form: 'Stock Adjustment',
        entityType: 'StockAdjustment',
        entityId: adj._id.toString(),
        action: 'Saved',
        entryNo: adj.adjustmentNo || 'ADJ-' + adj._id.toString().slice(-6),
        salesType: 'Adjustment',
        voucherType: 'Stock Adjustment',
        editedDate: formatDate(d),
        editedTime: formatTime(d),
        eventTime: formatTime(d),
        oldAmount: 0,
        newAmount: amount,
        systemName: 'POS-TERM-01',
        details: `Stock Adjustment ${adj.adjustmentNo || ''} - ${adj.reason || 'Inventory audit'}`,
        after: {
          adjustmentNo: adj.adjustmentNo,
          grandTotal: amount,
          reason: adj.reason,
        },
      });
      adjCreated++;
    }
  }
  console.log(`Backfilled ${adjCreated} StockAdjustment audit logs`);

  const totalLogs = await AuditLog.countDocuments();
  console.log(`Total AuditLog records now: ${totalLogs}`);

  await mongoose.disconnect();
}

backfill().catch(console.error);
